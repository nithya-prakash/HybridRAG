#!/usr/bin/env python
"""Fine-tunes the production cross-encoder reranker
(`cross-encoder/ms-marco-MiniLM-L-6-v2`, same base model app/core/reranker.py
loads) on the training split generated by generate_training_data.py, using
sentence-transformers' native CrossEncoder training API (already present at
sentence-transformers>=5.7.0, already a locked dependency — no version bump
needed) with `BinaryCrossEntropyLoss`, the same loss family MS MARCO
cross-encoders like the base model itself were originally trained with.

Does NOT touch the LLM (chat/judge backend) in any way — this script only
ever imports/constructs `CrossEncoder`.

CPU-only by default (`use_cpu=True`), matching this project's existing
CPU-only torch pin (backend/pyproject.toml) — GPU acceleration is available
automatically if CUDA is present (set `--use-gpu` to opt in) but is not
required or assumed anywhere else in this repo.

Reproducibility: every source of randomness (`random`, `numpy`, `torch`, and
the HF Trainer's own `seed=`) is pinned to the same fixed seed
(TRAINING_SEED). Given the tiny dataset (~200 examples) this is fast even on
CPU — a few minutes, not hours.

Run from backend/ (after generate_training_data.py has produced
eval/reranker_training/data/{train,calibration}.jsonl):
    uv run python ../eval/reranker_training/train_reranker.py
"""

from __future__ import annotations

import argparse
import json
import random
import subprocess
import sys
from datetime import UTC, datetime
from pathlib import Path

_REPO_ROOT = Path(__file__).resolve().parent.parent.parent
for _p in (_REPO_ROOT, _REPO_ROOT / "backend"):
    if str(_p) not in sys.path:
        sys.path.insert(0, str(_p))

DATA_DIR = Path(__file__).parent / "data"
MODELS_DIR = Path(__file__).parent / "models"

BASE_MODEL = "cross-encoder/ms-marco-MiniLM-L-6-v2"
TRAINING_SEED = 42
NUM_TRAIN_EPOCHS = 4
PER_DEVICE_TRAIN_BATCH_SIZE = 16
LEARNING_RATE = 2e-5
WARMUP_RATIO = 0.1


def _set_all_seeds(seed: int) -> None:
    import numpy as np
    import torch

    random.seed(seed)
    np.random.seed(seed)
    torch.manual_seed(seed)


def _load_jsonl(path: Path) -> dict[str, list]:
    queries, passages, labels = [], [], []
    with path.open() as f:
        for line in f:
            row = json.loads(line)
            queries.append(row["query"])
            passages.append(row["passage"])
            labels.append(float(row["label"]))
    return {"query": queries, "passage": passages, "label": labels}


def _git_commit() -> str | None:
    try:
        return (
            subprocess.check_output(
                ["git", "rev-parse", "HEAD"], cwd=_REPO_ROOT, stderr=subprocess.DEVNULL
            )
            .decode()
            .strip()
        )
    except Exception:  # noqa: BLE001 - metadata only, never fatal to a real training run
        return None


def train(use_gpu: bool) -> dict:
    _set_all_seeds(TRAINING_SEED)

    from datasets import Dataset
    from sentence_transformers.cross_encoder import (
        CrossEncoder,
        CrossEncoderTrainer,
        CrossEncoderTrainingArguments,
    )
    from sentence_transformers.cross_encoder.losses import BinaryCrossEntropyLoss

    train_path = DATA_DIR / "train.jsonl"
    calibration_path = DATA_DIR / "calibration.jsonl"
    stats_path = DATA_DIR / "dataset_stats.json"
    if not train_path.exists():
        print(
            f"ERROR: {train_path} not found — run generate_training_data.py first.",
            file=sys.stderr,
        )
        raise SystemExit(1)

    dataset_stats = json.loads(stats_path.read_text()) if stats_path.exists() else {}

    train_dataset = Dataset.from_dict(_load_jsonl(train_path))
    eval_dataset = Dataset.from_dict(_load_jsonl(calibration_path))

    model = CrossEncoder(BASE_MODEL, num_labels=1)
    loss = BinaryCrossEntropyLoss(model)

    output_dir = MODELS_DIR / "finetuned"
    args = CrossEncoderTrainingArguments(
        output_dir=str(MODELS_DIR / "_trainer_checkpoints"),
        num_train_epochs=NUM_TRAIN_EPOCHS,
        per_device_train_batch_size=PER_DEVICE_TRAIN_BATCH_SIZE,
        per_device_eval_batch_size=PER_DEVICE_TRAIN_BATCH_SIZE,
        learning_rate=LEARNING_RATE,
        warmup_ratio=WARMUP_RATIO,
        seed=TRAINING_SEED,
        data_seed=TRAINING_SEED,
        use_cpu=not use_gpu,
        fp16=False,
        bf16=False,
        logging_steps=5,
        eval_strategy="epoch",
        save_strategy="no",
        report_to="none",
        disable_tqdm=False,
    )

    trainer = CrossEncoderTrainer(
        model=model,
        args=args,
        train_dataset=train_dataset,
        eval_dataset=eval_dataset,
        loss=loss,
    )
    train_result = trainer.train()

    output_dir.mkdir(parents=True, exist_ok=True)
    model.save_pretrained(str(output_dir))

    log_history = [
        {k: v for k, v in entry.items() if isinstance(v, (int, float, str))}
        for entry in trainer.state.log_history
    ]

    metadata = {
        "generated_at": datetime.now(UTC).isoformat(),
        "git_commit": _git_commit(),
        "base_model": BASE_MODEL,
        "training_seed": TRAINING_SEED,
        "device": "gpu" if use_gpu else "cpu",
        "hyperparameters": {
            "num_train_epochs": NUM_TRAIN_EPOCHS,
            "per_device_train_batch_size": PER_DEVICE_TRAIN_BATCH_SIZE,
            "learning_rate": LEARNING_RATE,
            "warmup_ratio": WARMUP_RATIO,
            "loss": "BinaryCrossEntropyLoss",
        },
        "dataset_stats": dataset_stats,
        "final_train_loss": train_result.training_loss,
        "log_history": log_history,
        "checkpoint_path": str(output_dir),
    }
    (MODELS_DIR / "training_metadata.json").write_text(json.dumps(metadata, indent=2))
    return metadata


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--use-gpu",
        action="store_true",
        help="use CUDA if available instead of forcing CPU (default: CPU-only)",
    )
    args = parser.parse_args()

    metadata = train(use_gpu=args.use_gpu)

    print()
    print("=" * 72)
    print("RERANKER FINE-TUNING COMPLETE")
    print("=" * 72)
    print(f"base model      : {metadata['base_model']}")
    print(f"device          : {metadata['device']}")
    print(f"seed            : {metadata['training_seed']}")
    print(f"final train loss: {metadata['final_train_loss']:.4f}")
    print("eval loss by epoch:")
    for entry in metadata["log_history"]:
        if "eval_loss" in entry:
            print(f"  epoch {entry.get('epoch', '?'):.1f}: eval_loss={entry['eval_loss']:.4f}")
    print(f"checkpoint saved to: {metadata['checkpoint_path']}")
    print(f"metadata written to: {MODELS_DIR / 'training_metadata.json'}")
    print("=" * 72)


if __name__ == "__main__":
    main()
